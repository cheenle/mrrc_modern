#!/usr/bin/env python3
"""Publish one MRRC-Passport firmware build into the box's own catalog.

The box flashes a **single** file at offset 0 (bootloader + partition table + app
laid out at their real offsets, everything else 0xFF — i.e. exactly what
`esptool merge_bin` produces from `build/flash_args`).  This tool derives that
merged image from an ESP-IDF build directory and appends/updates the entry in
`downloads/passport/firmware.json`.

Why a **separate** catalog instead of `latest.json`: a bad firmware entry must not
be able to poison the update channel.  The box's `upgrade_core` parses
`latest.json` for its own line; a malformed Passport row in there would make an
entire release un-installable.  Two files, two blast radii.

The merge is done here in plain Python rather than by shelling out to `esptool`
so publishing works on a machine that has no ESP toolchain — and so the byte
layout can be asserted by a test instead of trusted to a CLI.

Usage:
    dev_tools/make_passport_firmware.py --build ~/HAM/mrrc-passport/build \\
        --version 1.2.1 --notes "AP 配网 + 频道回放" \\
        --out ~/HAM/hub/mrrc_modern/downloads/passport

It prints the upload recipe; it never uploads (the deploy step is the release
skill's job, with a server-side hash check before `mv`).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shlex
import sys
from pathlib import Path

CATALOG = "firmware.json"
#: Everything a Passport build's flash_args names, in the order ESP-IDF writes it.
REQUIRED = ("bootloader/bootloader.bin", "partition_table/partition-table.bin")


class BuildError(RuntimeError):
    pass


def parse_flash_args(text: str) -> tuple[dict[str, str], dict[str, str]]:
    """`build/flash_args` → (options, {offset: relative path}).

    Parsed as **data**, never executed: the file is generated by the build, but a
    publishing tool that `eval`s a text file is a publishing tool that runs
    whatever is in it.
    """
    options: dict[str, str] = {}
    images: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        parts = shlex.split(line)
        if parts[0].startswith("--"):
            # ESP-IDF writes `--flash_mode dio --flash_freq 80m` (space-separated);
            # `--key=value` is accepted too because hand-edited files exist.
            i = 0
            while i < len(parts):
                token = parts[i]
                if not token.startswith("--"):
                    i += 1
                    continue
                key = token[2:]
                if "=" in key:
                    key, _, value = key.partition("=")
                elif i + 1 < len(parts) and not parts[i + 1].startswith("--"):
                    value = parts[i + 1]
                    i += 1
                else:
                    value = "1"
                options[key] = value
                i += 1
            continue
        images[parts[0]] = parts[1]
    if not images:
        raise BuildError("flash_args names no images")
    return options, images


def merge_images(build_dir: Path, images: dict[str, str]) -> bytes:
    """Lay every image at its offset into one buffer, 0xFF everywhere else."""
    placed = []
    for offset_text, rel in images.items():
        try:
            offset = int(offset_text, 0)
        except ValueError as e:
            raise BuildError(f"bad offset {offset_text!r}") from e
        src = build_dir / rel
        if not src.is_file():
            raise BuildError(f"missing image: {src}")
        placed.append((offset, src.read_bytes()))
    end = max(offset + len(blob) for offset, blob in placed)
    for name in REQUIRED:
        if not any(rel.endswith(name) for rel in images.values()):
            raise BuildError(f"flash_args does not place {name}")
    # 4 KB alignment of the tail: a reader that rounds the size up to a sector
    # then sees 0xFF, not a truncated image.
    total = (end + 0xFFF) & ~0xFFF
    merged = bytearray(b"\xff" * total)
    for offset, blob in placed:
        # An overlapping placement means the build's own flash_args is not what we
        # think it is; overwriting silently would produce a plausible bad image.
        if merged[offset:offset + len(blob)] != b"\xff" * len(blob):
            raise BuildError(f"images overlap at 0x{offset:x}")
        merged[offset:offset + len(blob)] = blob
    return bytes(merged)


def build_is_dirty(build_dir: Path) -> bool:
    """True when the app image's own `esp_app_desc_t` version carries `-dirty`.

    ESP-IDF stamps `git describe` into the image.  Publishing a `-dirty` build
    means publishing a binary nobody can reproduce: the version string in the
    catalog and the one inside the flash are the same string, so it lies to
    whoever reads it later looking for what shipped.
    """
    for name in ("mrrc-terminal.bin",):
        path = build_dir / name
        if not path.is_file():
            continue
        head = path.read_bytes()[:512]
        return b"-dirty" in head
    return False


def entry_for(version: str, blob: bytes, notes: str, chip: str = "esp32c3",
              base_url: str = "https://www.vlsc.net/mrrc_modern/downloads/passport") -> dict:
    digest = hashlib.sha256(blob).hexdigest()
    name = f"mrrc-terminal-{version}-merged.bin"
    return {
        "version": version,
        "chip": chip,
        "url": f"{base_url}/{name}",
        "size": len(blob),
        "sha256": digest,
        "notes": notes,
        "_filename": name,
    }


def update_catalog(catalog_path: Path, entry: dict) -> dict:
    """Insert/replace one version, newest first, and keep the file's other fields."""
    doc = {"product": "MRRC-Passport", "builds": []}
    if catalog_path.is_file():
        try:
            doc = json.loads(catalog_path.read_text(encoding="utf-8"))
        except ValueError as e:
            raise BuildError(f"{catalog_path} is not JSON: {e}") from e
    builds = [b for b in doc.get("builds", []) if b.get("version") != entry["version"]]
    clean = {k: v for k, v in entry.items() if not k.startswith("_")}
    builds.append(clean)

    def key(build: dict) -> tuple:
        try:
            return tuple(int(p) for p in str(build["version"]).split("."))
        except ValueError:
            return (0,)

    builds.sort(key=key, reverse=True)
    doc["builds"] = builds
    catalog_path.parent.mkdir(parents=True, exist_ok=True)
    catalog_path.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n",
                            encoding="utf-8")
    return doc


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--build", required=True, help="ESP-IDF build directory")
    parser.add_argument("--version", required=True, help="firmware version, e.g. 1.2.1")
    parser.add_argument("--notes", default="", help="one line for the page")
    parser.add_argument("--chip", default="esp32c3")
    parser.add_argument("--out", required=True,
                        help="downloads/passport directory (catalog + image)")
    parser.add_argument("--base-url",
                        default="https://www.vlsc.net/mrrc_modern/downloads/passport")
    parser.add_argument("--allow-dirty", action="store_true",
                        help="publish a `-dirty` build anyway (only for a bench test)")
    args = parser.parse_args(argv)

    build_dir = Path(args.build).expanduser()
    flash_args = build_dir / "flash_args"
    if not flash_args.is_file():
        print(f"error: {flash_args} not found (build the firmware first)", file=sys.stderr)
        return 2
    if build_is_dirty(build_dir) and not args.allow_dirty:
        print("error: this build is stamped `-dirty` — commit (or stash) the firmware "
              "sources and rebuild, or pass --allow-dirty for a bench test",
              file=sys.stderr)
        return 2
    try:
        _options, images = parse_flash_args(flash_args.read_text(encoding="utf-8"))
        blob = merge_images(build_dir, images)
    except BuildError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    out = Path(args.out).expanduser()
    entry = entry_for(args.version, blob, args.notes, args.chip, args.base_url)
    image_path = out / entry["_filename"]
    out.mkdir(parents=True, exist_ok=True)
    image_path.write_bytes(blob)
    doc = update_catalog(out / CATALOG, entry)

    print(f"image   {image_path}  ({len(blob)} B)")
    print(f"sha256  {entry['sha256']}")
    print(f"catalog {out / CATALOG}  ({len(doc['builds'])} build(s))")
    print("\nupload (verify the hash on the server before mv):")
    print(f"  scp {image_path} {out / CATALOG} www.vlsc.net:/var/tmp/")
    print("  ssh www.vlsc.net 'sha256sum /var/tmp/"
          f"{entry['_filename']}'  # expect {entry['sha256']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
