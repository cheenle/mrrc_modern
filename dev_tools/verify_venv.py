#!/usr/bin/env python3
"""Verify an installed virtualenv against pip's own RECORD hashes — and repair it.

Why this exists
---------------
Every wheel install writes one sha256 per file into
``<dist>-<version>.dist-info/RECORD``.  If a write is truncated (a full
filesystem, a reset mid-install, a marginal flash block) **pip still reports
success**, and nothing notices until the module is imported at run time.

That is not hypothetical: on 2026-11-01 a customer box (W103D + FT-991A,
support bundle ``20261031-171247-5ec1``) had shipped with
``numpy/random/mtrand*.so`` and ``scipy/linalg/_flapack*.so`` truncated.  Both
files still began with the ELF magic and `import numpy` / `import scipy` still
worked, so the import gate was green.  What actually failed was:

    >>> import numpy.random
    UnicodeDecodeError: 'utf-8' codec can't decode byte 0x80 in position 0

``ft8.runtime`` imports ``scipy.signal``, which imports ``numpy.random``, so the
whole FT8 mode was silently composed out — ``FT8 composition failed — running
SSB-only`` on 50 of 50 startups, with every ``/api/ft8/*`` request answering an
unhandled ``RuntimeError``.  The radio itself was fine.

Verify is cheap (a few seconds on the box, under a second on a build host) and
is part of the image build (``install.sh``), so a damaged venv fails the build
instead of a customer.

Usage
-----
    python3 dev_tools/verify_venv.py                  # verify; exit 1 if damaged
    python3 dev_tools/verify_venv.py --verbose
    python3 dev_tools/verify_venv.py --repair         # reinstall the damaged dists
    python3 dev_tools/verify_venv.py --path /some/venv/lib/python3.11/site-packages

``--repair`` runs ``pip install --force-reinstall --no-deps --only-binary :all:``
for each damaged distribution, pinned to the version already installed, then
verifies again.  Stdlib only: it must run on a box whose numpy is the problem.
"""
from __future__ import annotations

import argparse
import base64
import csv
import glob
import hashlib
import os
import subprocess
import sys
from typing import Iterable, NamedTuple


SUMMARY = "Verify an installed virtualenv against pip's own RECORD hashes, and repair it."


class Damage(NamedTuple):
    """One file that does not match the hash pip recorded for it."""

    dist: str
    version: str
    path: str
    problem: str


def _hash_file(path: str) -> tuple[str, str]:
    """pip records ``sha256=<urlsafe-b64, no padding>``.

    Returns ``(digest, problem)``: a missing or unreadable file is reported
    rather than raised, because it is a *finding*, not an error in this tool.
    """
    digest = hashlib.sha256()
    try:
        with open(path, "rb") as handle:
            for block in iter(lambda: handle.read(1 << 20), b""):
                digest.update(block)
    except FileNotFoundError:
        return "", "missing"
    except OSError as exc:
        return "", f"unreadable ({exc})"
    return base64.urlsafe_b64encode(digest.digest()).rstrip(b"=").decode(), ""


def _dist_name_version(record_path: str) -> tuple[str, str]:
    """``numpy-2.2.6.dist-info/RECORD`` → ``("numpy", "2.2.6")``.

    The trailing ``.dist-info`` is stripped first, then the *last* dash splits
    name from version, so a normalised name containing dashes still works.
    """
    stem = os.path.basename(os.path.dirname(record_path))
    if stem.endswith(".dist-info"):
        stem = stem[: -len(".dist-info")]
    name, _, version = stem.rpartition("-")
    return (name or stem), version


def _should_skip(rel_path: str) -> bool:
    """Entries whose bytes legitimately differ from the wheel's.

    ``__pycache__`` is regenerated by the interpreter (and pip records the
    compiled file it wrote), so a recompile is not damage — that false positive
    showed up on the field box right after the real repair and would have made
    every run "dirty".
    """
    return "__pycache__" in rel_path.split("/") or rel_path.endswith(".pyc")


def scan(site_packages: str, verbose: bool = False) -> tuple[list[Damage], int]:
    """Verify every RECORD under ``site_packages``; return (damage, files_checked)."""
    damage: list[Damage] = []
    checked = 0
    for record in sorted(glob.glob(os.path.join(site_packages, "*.dist-info", "RECORD"))):
        dist, version = _dist_name_version(record)
        dist_checked = 0
        try:
            with open(record, newline="", encoding="utf-8") as handle:
                rows = list(csv.reader(handle))
        except OSError as exc:            # a damaged RECORD is itself damage
            damage.append(Damage(dist, version, record, f"unreadable RECORD ({exc})"))
            continue
        for row in rows:
            if len(row) < 2 or not row[1].startswith("sha256="):
                continue
            rel_path, expected = row[0], row[1].split("=", 1)[1]
            if _should_skip(rel_path):
                continue
            absolute = os.path.join(site_packages, rel_path)
            dist_checked += 1
            actual, problem = _hash_file(absolute)
            if problem:
                damage.append(Damage(dist, version, rel_path, problem))
                continue
            if actual != expected:
                damage.append(Damage(dist, version, rel_path, "hash mismatch"))
        checked += dist_checked
        if verbose and dist_checked:
            print(f"  {dist} {version}: {dist_checked} files")
    return damage, checked


def damaged_distributions(damage: Iterable[Damage]) -> list[tuple[str, str]]:
    """The distinct (name, version) pairs to reinstall, in first-seen order."""
    seen: dict[tuple[str, str], None] = {}
    for item in damage:
        seen.setdefault((item.dist, item.version), None)
    return list(seen)


def repair(site_packages: str, damage: list[Damage]) -> int:
    """Force-reinstall each damaged distribution.  Returns a process exit code."""
    targets = damaged_distributions(damage)
    if not targets:
        return 0
    failed = 0
    for dist, version in targets:
        spec = f"{dist}=={version}" if version else dist
        print(f"repair: {spec}", flush=True)
        command = [
            sys.executable, "-m", "pip", "install",
            "--force-reinstall", "--no-deps", "--only-binary", ":all:",
            "--disable-pip-version-check", spec,
        ]
        result = subprocess.run(command, check=False)  # noqa: S603 - fixed argv
        if result.returncode != 0:
            print(f"repair: {spec} FAILED (exit {result.returncode})", file=sys.stderr)
            failed += 1
    return 1 if failed else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=SUMMARY)
    parser.add_argument(
        "--path", default=None,
        help="site-packages to check (default: this interpreter's)",
    )
    parser.add_argument("--verbose", action="store_true", help="print every distribution")
    parser.add_argument("--repair", action="store_true",
                        help="pip --force-reinstall every damaged distribution")
    args = parser.parse_args(argv)

    site_packages = args.path or _default_site_packages()
    if not site_packages or not os.path.isdir(site_packages):
        print(f"verify-venv: no site-packages at {site_packages!r}", file=sys.stderr)
        return 2

    print(f"verify-venv: checking {site_packages}", flush=True)
    damage, checked = scan(site_packages, verbose=args.verbose)
    if not damage:
        print(f"verify-venv: OK — {checked} files match their RECORD hashes")
        return 0

    print(f"verify-venv: {len(damage)} damaged file(s) out of {checked}:", file=sys.stderr)
    for item in damage:
        print(f"  {item.dist} {item.version}: {item.path} — {item.problem}", file=sys.stderr)

    if not args.repair:
        print(
            "verify-venv: a truncated wheel install looks fine to pip and to an\n"
            "`import numpy` smoke test, so this must not ship.  Re-run with --repair.",
            file=sys.stderr,
        )
        return 1

    if repair(site_packages, damage) != 0:
        return 1
    damage_after, checked_after = scan(site_packages)
    if damage_after:
        print(f"verify-venv: still {len(damage_after)} damaged file(s) after repair",
              file=sys.stderr)
        return 1
    print(f"verify-venv: repaired — {checked_after} files match their RECORD hashes")
    return 0


def _default_site_packages() -> str:
    """This interpreter's site-packages (venv-aware)."""
    import site

    candidates = [p for p in site.getsitepackages() if p.endswith("site-packages")]
    return candidates[0] if candidates else ""


if __name__ == "__main__":
    raise SystemExit(main())
