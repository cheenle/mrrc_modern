#!/usr/bin/env bash
# Vendor the Boost header closure that WSJT-X's crc13.cpp / crc14.cpp need.
#
# Why this exists: <boost/crc.hpp> is the only Boost use in the DSP tree, and
# Debian ships it inside libboost1.74-dev — 138 MB of headers, installed into
# both appliance images and into every macOS/Windows build machine, to compile
# two files.  Vendoring the closure (a hundred small headers, well under 1 MB)
# removes the dependency from all four platforms and takes 138 MB out of the
# W103D and Raspberry Pi rootfs.
#
# The file list is NOT hand-maintained: it is the recursive include closure of
# boost/crc.hpp + boost/config.hpp, which are the two headers crc13.cpp and
# crc14.cpp include.  Only includes that resolve to a path starting with
# "boost/" are followed; <cstddef> and friends come from the compiler.
#
# usage: tools/ft8/vendor_boost_headers.sh <include-root> [out-dir]
#   e.g. tools/ft8/vendor_boost_headers.sh /usr/include
set -euo pipefail

INCLUDE="${1:?usage: vendor_boost_headers.sh <include-root> [out-dir]}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DEST="${2:-$REPO_ROOT/ft8/dsp/vendor-boost}"
[ -d "$INCLUDE/boost" ] || { echo "no boost/ under $INCLUDE" >&2; exit 1; }

rm -rf "$DEST"
python3 - "$INCLUDE" "$DEST" <<'PY'
import re
import shutil
import sys
from pathlib import Path

include_root, dest = Path(sys.argv[1]), Path(sys.argv[2])
roots = ["boost/crc.hpp", "boost/config.hpp"]
include_re = re.compile(r'^\s*#\s*include\s*[<"]([^>"]+)[>"]', re.M)

seen, queue = set(), list(roots)
while queue:
    name = queue.pop()
    src = include_root / name
    if not src.is_file():
        # Boost config headers pull in a handful of names that this packaging
        # does not carry (a standalone asio header, a versioned detail header
        # of another library).  Anything the C++ compiler itself provides is
        # not boost/* and is filtered below; a *missing* boost/* file is a
        # real error worth stopping for.
        raise SystemExit(f"missing include in the closure: {name}")
    if name in seen:
        continue
    seen.add(name)
    for match in include_re.finditer(src.read_text(errors="replace")):
        target = match.group(1)
        if not target.startswith("boost/"):
            continue
        # Resolved against the include root, not the including file's directory:
        # these are all angle-bracket includes (boost/config.hpp writes
        # <boost/config/detail/suffix.hpp>), and Boost's own layout puts every
        # one of them under boost/ at the root.
        resolved = (include_root / target).resolve()
        try:
            rel = resolved.relative_to(include_root.resolve())
        except ValueError:
            continue
        queue.append(str(rel))

for name in sorted(seen):
    out = dest / name
    out.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(include_root / name, out)
print(f"vendored {len(seen)} boost headers")
PY

# The Boost Software License requires the notice to travel with the headers:
# every vendored file carries the banner, and this is the referenced text.
# Debian's libboost1.74-dev ships no LICENSE_1_0.txt (dpkg -L has none), so the
# canonical text is written here when the host has no copy to copy.
LICENSE_CANDIDATES=(
    "$INCLUDE/../share/doc/libboost1.74-dev/LICENSE_1_0.txt"
    "$INCLUDE/../share/doc/libboost-dev/LICENSE_1_0.txt"
    "$INCLUDE/../share/doc/boost/LICENSE_1_0.txt"
    "$INCLUDE/boost/LICENSE_1_0.txt"
)
for candidate in "${LICENSE_CANDIDATES[@]}"; do
    if [ -f "$candidate" ]; then
        cp "$candidate" "$DEST/LICENSE_1_0.txt"
        break
    fi
done
if [ ! -f "$DEST/LICENSE_1_0.txt" ]; then
    cat >"$DEST/LICENSE_1_0.txt" <<'LICENSE'
