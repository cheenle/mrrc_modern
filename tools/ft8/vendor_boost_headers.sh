cd "$DEST"
if command -v sha256sum >/dev/null 2>&1; then
    HASH=(sha256sum)
else
    HASH=(shasum -a 256)
fi
find . -type f | sed 's|^\./||' | sort | xargs "${HASH[@]}" > "$DEST.sha256"
echo "wrote $DEST and $DEST.sha256"
